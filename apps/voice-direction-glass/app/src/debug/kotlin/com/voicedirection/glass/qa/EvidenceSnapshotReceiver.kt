        val microphoneDisclosureAccepted: Boolean,
        val microphoneDisclosureVersion: String,
        val enabledAlertChannelCount: Int,
        val phoneNotificationEnabled: Boolean,
        val phoneVibrationEnabled: Boolean,
        val ttsEnabled: Boolean,
        val metaDisplayEnabled: Boolean,
        val androidXrDisplayEnabled: Boolean,
        val latencyEventCount: Int,
        val latestProcessingLatencyMillis: Long,
        val averageProcessingLatencyMillis: Long,
        val latencyOverTargetCount: Int,
        val feedbackCount: Int,
        val feedbackCorrect: Int,
        val feedbackFalsePositive: Int,
        val feedbackWrongDirection: Int,
        val feedbackWrongSpeaker: Int,
        val directionTrialCount: Int,
        val directionRequiredTrialsPerDirection: Int,
        val directionRequiredTotalTrials: Int,
        val directionMissingTotalTrials: Int,
        val directionControlledTrialTargetComplete: Boolean,
        val directionMatched: Int,
        val directionMismatched: Int,
        val directionUnknownOrUnusable: Int,
        val directionFrontTrials: Int,
        val directionBackTrials: Int,
        val directionLeftTrials: Int,
        val directionRightTrials: Int,
        val directionFrontMissingTrials: Int,
